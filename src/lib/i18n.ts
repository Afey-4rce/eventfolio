/** Hook that returns a `t()` function for the current language. */
export function useTranslation() {
  const language = useAppStore((s) => s.language);
  const t = (key: TranslationKey, vars?: Record<string, string | number>): string => {
    const en = translations.en[key] ?? key;
    const str = (translations[language] as Record<string, string>)?.[key] ?? en;
    if (!vars) return str;
    return Object.entries(vars).reduce((acc, [k, v]) => acc.replace(`{${k}}`, String(v)), str);
  };
  return { t, language };
}
